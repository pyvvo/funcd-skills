#!/usr/bin/env python3
"""Regenerate the funcd skill's docs index and references from the docs site.

The docs site (https://pyvvo.github.io/funcd) describes funcd's latest release and serves an llms.txt and a Markdown
copy of every page. This script reads them and writes:

- the docs index inside skills/funcd/SKILL.md, between the docs-index markers, and the release it describes;
- skills/funcd/references/<page>.md, one file per Usage page, for agents with no network;
- AGENTS.md, the same rules and index for agents that read AGENTS.md instead of skills.

    python3 scripts/generate.py                      # from the live site
    python3 scripts/generate.py --build <dir>        # from a local site build (build/client)
    python3 scripts/generate.py --check              # exit 1 when the files differ from what the site gives
"""

from __future__ import annotations

import argparse
import re
import sys
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKILL = ROOT / "skills" / "funcd" / "SKILL.md"
REFS = ROOT / "skills" / "funcd" / "references"
AGENTS = ROOT / "AGENTS.md"
AGENTS_TEMPLATE = ROOT / "scripts" / "agents-template.md"

SITE = "https://pyvvo.github.io/funcd"
ORIGIN = "https://pyvvo.github.io"
# The llms.txt sections the index keeps; the API reference is one link, since funcdctl covers its operations.
KEEP = ("Introduction", "Get started", "Develop")
API_LINE = f"- [API reference]({SITE}/docs/api.md): every operation of the control plane API and what it answers."
INDEX_START = "<!-- docs-index:start (generated by scripts/generate.py) -->"
INDEX_END = "<!-- docs-index:end -->"
REFS_START = "<!-- references:start (generated by scripts/generate.py) -->"
REFS_END = "<!-- references:end -->"
# A reference file longer than this starts with a table of contents (Agent Skills best practices: over 100 lines).
TOC_MIN_LINES = 100

LINK = re.compile(r"\[([^\]]+)\]\((/funcd/[^)\s]+)\)")
ANCHOR = re.compile(r" \[#[^\]]+\]$")
RELEASE = re.compile(r"FUNCDCTL_VERSION=(v\d+\.\d+\.\d+)")


class Source:
    """Reads site paths (such as /llms.txt) from the live site or from a local build."""

    def __init__(self, build: Path | None) -> None:
        self.build = build

    def read(self, path: str) -> str:
        if self.build is not None:
            file = self.build / path.removeprefix("/funcd/").lstrip("/")
            if not file.is_file():
                sys.exit(f"generate: {file} is missing from the build; build the site first")
            return file.read_text()
        url = SITE + "/" + path.removeprefix("/funcd/").lstrip("/")
        try:
            with urllib.request.urlopen(url, timeout=30) as resp:
                return resp.read().decode()
        except urllib.error.URLError as err:
            sys.exit(f"generate: cannot read {url}: {err}")


def absolute(text: str) -> str:
    """Site-relative links (/funcd/...) become absolute, so they work from a skill folder."""
    return LINK.sub(lambda m: f"[{m.group(1)}]({ORIGIN}{m.group(2)})", text)


def index_lines(llms: str) -> list[str]:
    """The Get started and Develop entries of llms.txt, links made absolute."""
    out, keep = [], False
    for line in llms.splitlines():
        # A section is an H2 (llmstxt.org), or a bold list item in the site's builds before it followed the spec.
        top = re.match(r"^(?:## (.+)|- \*\*(.+)\*\*)$", line)
        if top:
            section = top.group(1) or top.group(2)
            keep = section in KEEP
            if keep:
                out.append(f"- **{section}**")
            continue
        if line.startswith("# ") or line.startswith("> "):
            continue
        if line.startswith("- ") and not line.startswith("- **"):
            keep = keep and "API reference" not in line
            if not keep:
                continue
        if keep and line.strip():
            out.append(absolute(line))
    if not out:
        sys.exit("generate: llms.txt holds no Get started or Develop section")
    out.append(API_LINE)
    return out


def usage_pages(lines: list[str]) -> list[tuple[str, str]]:
    """(title, site path) of every Usage page in the index: each .md that is not a Spec tab."""
    pages = []
    for line in lines:
        m = re.search(r"\[([^\]]+)\]\(" + re.escape(ORIGIN) + r"(/funcd/docs/[^)]+\.md)\)", line)
        if m and not m.group(2).endswith("/spec.md") and "/docs/api" not in m.group(2):
            pages.append((m.group(1), m.group(2)))
    return pages


def ref_name(path: str) -> str:
    slug = path.removeprefix("/funcd/docs/").removesuffix(".md")
    for prefix in ("develop/", "get-started/"):
        slug = slug.removeprefix(prefix)
    return slug.replace("/", "-") + ".md"


def reference(text: str, url: str) -> str:
    lines = [ANCHOR.sub("", line) for line in absolute(text).splitlines()]
    lines = [line for line in lines if not line.startswith("URL: ")]
    title, body = lines[0], lines[1:]
    head = [title, "", f"Source: {url} (the Markdown copy of the page; prefer it when the network is up)."]
    if len(lines) > TOC_MIN_LINES:
        sections = [line[3:] for line in body if line.startswith("## ")]
        if sections:
            head += ["", "## Contents", ""] + [f"- {s}" for s in sections]
    return "\n".join(head + body).rstrip() + "\n"


def replace_block(text: str, start: str, end: str, block: str, where: Path) -> str:
    i, j = text.find(start), text.find(end)
    if i < 0 or j < i:
        sys.exit(f"generate: {where} lacks the markers {start!r} … {end!r}")
    return text[: i + len(start)] + "\n" + block.rstrip() + "\n" + text[j:]


def set_release(text: str, release: str) -> str:
    new, n = re.subn(r'(\n  docs-release: )"[^"]*"', rf'\1"{release}"', text, count=1)
    if n != 1:
        sys.exit("generate: SKILL.md frontmatter lacks metadata.docs-release")
    return new


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--build", type=Path, help="a local site build (packages/docs/build/client) instead of the site")
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 when a file would change")
    args = ap.parse_args()
    src = Source(args.build)

    lines = index_lines(src.read("/llms.txt"))
    m = RELEASE.search(src.read("/docs/get-started/install.md"))
    if not m:
        sys.exit("generate: the Install page names no release (FUNCDCTL_VERSION=vX.Y.Z)")
    release = m.group(1)

    wanted: dict[Path, str] = {}
    refs = []
    for title, path in usage_pages(lines):
        name = ref_name(path)
        wanted[REFS / name] = reference(src.read(path), ORIGIN + path)
        refs.append(f"- [{title}](references/{name})")

    index = "\n".join(lines)
    skill = SKILL.read_text()
    skill = replace_block(skill, INDEX_START, INDEX_END, index, SKILL)
    skill = replace_block(skill, REFS_START, REFS_END, "\n".join(refs), SKILL)
    wanted[SKILL] = set_release(skill, release)
    wanted[AGENTS] = AGENTS_TEMPLATE.read_text().replace("{{RELEASE}}", release).replace("{{INDEX}}", index)

    stale = sorted(p for p in REFS.glob("*.md") if p not in wanted)
    changed = [p for p, body in wanted.items() if not p.is_file() or p.read_text() != body]
    if args.check:
        for p in changed + stale:
            print(f"out of date: {p.relative_to(ROOT)}")
        return 1 if changed or stale else 0
    REFS.mkdir(parents=True, exist_ok=True)
    for p in stale:
        p.unlink()
    for p in changed:
        p.write_text(wanted[p])
    print(f"docs {release}: {len(refs)} references, {len(changed)} files written, {len(stale)} removed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
